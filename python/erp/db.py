"""
가상 ERP 저장소: 같은 PostgreSQL 의 별도 스키마 erp.

백엔드(Flyway)는 public 스키마만 관리하고, erp 스키마는 이 서비스가 직접 만든다.
두 시스템은 서로의 테이블을 읽지 않고 API 로만 주고받는다 (실제 공장의 ERP 와 MES 처럼).

접속 정보: 환경변수 ERP_DB_URL 이 있으면 그것을, 없으면 백엔드 설정(application.yml 의 URL · 사용자,
git 제외 application-local.yml 의 비밀번호)을 읽는다. 비밀번호를 다른 파일로 복사하지 않기 위해서다.
"""
from __future__ import annotations

import os
from pathlib import Path

import psycopg
import yaml
from psycopg.rows import dict_row

from . import masterdata as md

RESOURCES = Path(__file__).resolve().parents[2] / "backend" / "src" / "main" / "resources"

SCHEMA = """
CREATE SCHEMA IF NOT EXISTS erp;

CREATE TABLE IF NOT EXISTS erp.item (
    code           varchar(16) PRIMARY KEY,
    name           varchar(100) NOT NULL,
    type           varchar(4)   NOT NULL CHECK (type IN ('FG', 'RM', 'PM')),
    uom            varchar(8)   NOT NULL,
    unit_cost      numeric(12, 2) NOT NULL,
    lead_time_days int          NOT NULL,
    safety_stock   numeric(12, 3) NOT NULL
);
CREATE TABLE IF NOT EXISTS erp.bom (
    fg_code        varchar(16) REFERENCES erp.item (code),
    component_code varchar(16) REFERENCES erp.item (code),
    qty_per        numeric(12, 6) NOT NULL,
    PRIMARY KEY (fg_code, component_code)
);
CREATE TABLE IF NOT EXISTS erp.inventory (
    item_code varchar(16) PRIMARY KEY REFERENCES erp.item (code),
    on_hand   numeric(14, 4) NOT NULL,
    allocated numeric(14, 4) NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS erp.inventory_txn (
    id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_code varchar(16) NOT NULL,
    kind      varchar(16) NOT NULL CHECK (kind IN ('OPENING', 'RECEIPT', 'ALLOCATE', 'ISSUE')),
    qty       numeric(14, 4) NOT NULL,
    ref       varchar(32),
    at        timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS erp.sales_order (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no   varchar(16),
    customer   varchar(100) NOT NULL,
    item_code  varchar(16) NOT NULL REFERENCES erp.item (code),
    qty        int NOT NULL CHECK (qty > 0),
    due_date   date NOT NULL,
    status     varchar(16) NOT NULL CHECK (status IN ('OPEN', 'PLANNED', 'IN_PRODUCTION', 'COMPLETED', 'SHIPPED')),
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS erp.production_order (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no       varchar(16),
    sales_order_id bigint REFERENCES erp.sales_order (id),
    item_code      varchar(16) NOT NULL,
    qty            int NOT NULL,
    batches        int NOT NULL,
    material_ready date NOT NULL,
    planned_start  date NOT NULL,
    planned_end    date NOT NULL,
    at_risk        boolean NOT NULL,
    risk_reason    varchar(200),
    planned_cost   bigint NOT NULL,
    status         varchar(16) NOT NULL CHECK (status IN ('PLANNED', 'RELEASED', 'IN_PROGRESS', 'COMPLETED', 'ON_HOLD')),
    created_at     timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS erp.production_material (
    production_order_id bigint REFERENCES erp.production_order (id),
    item_code           varchar(16) NOT NULL,
    required            numeric(14, 4) NOT NULL,
    allocated           numeric(14, 4) NOT NULL,
    shortage            numeric(14, 4) NOT NULL,
    PRIMARY KEY (production_order_id, item_code)
);
-- MES 연계: 생산 실적 (배치 1개 = 1행, 배치 번호로 중복 보고를 막는다)
ALTER TABLE erp.production_order ADD COLUMN IF NOT EXISTS produced_qty int NOT NULL DEFAULT 0;
ALTER TABLE erp.production_order ADD COLUMN IF NOT EXISTS batches_done int NOT NULL DEFAULT 0;
CREATE TABLE IF NOT EXISTS erp.production_actual (
    batch_id            varchar(32) PRIMARY KEY,
    production_order_id bigint NOT NULL REFERENCES erp.production_order (id),
    seq                 int NOT NULL,
    qty                 int NOT NULL,
    completed_at        timestamptz,
    received_at         timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS erp.purchase_order (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no            varchar(16),
    item_code           varchar(16) NOT NULL REFERENCES erp.item (code),
    qty                 numeric(14, 4) NOT NULL,
    unit_cost           numeric(12, 2) NOT NULL,
    expected_date       date NOT NULL,
    status              varchar(16) NOT NULL CHECK (status IN ('OPEN', 'RECEIVED')),
    production_order_id bigint REFERENCES erp.production_order (id),
    created_at          timestamptz NOT NULL DEFAULT now(),
    received_at         timestamptz
);
"""


def conninfo() -> str:
    url = os.environ.get("ERP_DB_URL")
    if url:
        return url
    base = yaml.safe_load((RESOURCES / "application.yml").read_text(encoding="utf-8"))["spring"]["datasource"]
    jdbc = base["url"].removeprefix("jdbc:")  # postgresql://localhost:5432/factory_demo
    password = os.environ.get("DB_PASSWORD")
    local = RESOURCES / "application-local.yml"
    if not password and local.exists():
        password = yaml.safe_load(local.read_text(encoding="utf-8"))["spring"]["datasource"].get("password")
    return psycopg.conninfo.make_conninfo(jdbc, user=base["username"], password=password or "")


def connect() -> psycopg.Connection:
    return psycopg.connect(conninfo(), row_factory=dict_row, autocommit=False)


def ensure_schema(conn: psycopg.Connection) -> bool:
    """스키마가 없으면 만들고 기초 데이터를 넣는다. 새로 만들었으면 True."""
    exists = conn.execute("SELECT to_regclass('erp.item') IS NOT NULL AS ok").fetchone()["ok"]
    conn.execute(SCHEMA)
    if not exists:
        seed(conn)
    conn.commit()
    return not exists


def reset(conn: psycopg.Connection) -> None:
    """
    데모용: 기초 데이터로 다시 시작한다. 번호(SO · PRD · PUR)는 이어서 매긴다 (CONTINUE IDENTITY):
    MES 에는 이미 받은 생산 지시가 남아 있어서, 같은 오더번호를 다시 쓰면 다른 오더가 섞인다.
    """
    conn.execute(SCHEMA)
    conn.execute("TRUNCATE erp.production_actual, erp.purchase_order, erp.production_material, erp.production_order,"
                 " erp.sales_order, erp.inventory_txn, erp.inventory, erp.bom, erp.item CONTINUE IDENTITY CASCADE")
    seed(conn)
    conn.commit()


def seed(conn: psycopg.Connection) -> None:
    from datetime import date, timedelta
    with conn.cursor() as cur:
        cur.executemany("INSERT INTO erp.item VALUES (%s, %s, %s, %s, %s, %s, %s)", md.ITEMS)
        cur.executemany("INSERT INTO erp.bom VALUES (%s, %s, %s)",
                        [(fg, code, qty) for fg, lines in md.BOM.items() for code, qty in lines])
        cur.executemany("INSERT INTO erp.inventory (item_code, on_hand) VALUES (%s, %s)",
                        [(code, md.OPENING_STOCK.get(code, 0)) for code, _, kind, *_ in md.ITEMS if kind != "FG"]
                        + [(code, 0) for code, _, kind, *_ in md.ITEMS if kind == "FG"])
        cur.executemany("INSERT INTO erp.inventory_txn (item_code, kind, qty, ref) VALUES (%s, 'OPENING', %s, '기초재고')",
                        list(md.OPENING_STOCK.items()))
        for customer, item, qty, days in md.SAMPLE_ORDERS:
            row = cur.execute("INSERT INTO erp.sales_order (customer, item_code, qty, due_date, status)"
                              " VALUES (%s, %s, %s, %s, 'OPEN') RETURNING id",
                              (customer, item, qty, date.today() + timedelta(days=days))).fetchone()
            cur.execute("UPDATE erp.sales_order SET order_no = %s WHERE id = %s", (f"SO-{row['id']:04d}", row["id"]))
