-- 교대 인수인계 리포트: 대시보드가 요청하면(PENDING) 에이전트가 해당 시간대 알람·조치를 요약해 채운다(DONE).

CREATE TABLE handover_report (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    window_from  timestamp(6) with time zone NOT NULL,
    window_to    timestamp(6) with time zone NOT NULL,
    status       varchar(16)  NOT NULL,
    requested_by varchar(64),
    generator    varchar(32),
    title        varchar(200),
    body         text,
    created_at   timestamp(6) with time zone NOT NULL,
    completed_at timestamp(6) with time zone,
    CONSTRAINT handover_report_status_check CHECK (status IN ('PENDING', 'DONE'))
);
CREATE INDEX idx_handover_report_created_at ON handover_report (created_at);
