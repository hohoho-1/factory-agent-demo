-- 기준 스키마: Flyway 도입 전 Hibernate(ddl-auto=update)가 만들어 둔 테이블 그대로.
-- 이미 테이블이 있는 DB는 baseline-on-migrate 로 이 파일을 건너뛰고(V1 로 기록), 빈 DB에서만 실행된다.

CREATE TABLE sensor_reading (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_id   varchar(32)      NOT NULL,
    equipment_type varchar(32)      NOT NULL,
    measured_at    timestamp(6) with time zone NOT NULL,
    metric         varchar(32)      NOT NULL,
    received_at    timestamp(6) with time zone NOT NULL,
    unit           varchar(16),
    value          double precision NOT NULL
);
CREATE INDEX idx_reading_eq_metric_time ON sensor_reading (equipment_id, metric, measured_at);

CREATE TABLE alarm (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cleared_at      timestamp(6) with time zone,
    direction       varchar(8)       NOT NULL,
    equipment_id    varchar(32)      NOT NULL,
    equipment_type  varchar(32)      NOT NULL,
    last_value      double precision NOT NULL,
    message         varchar(255)     NOT NULL,
    metric          varchar(32)      NOT NULL,
    peak_value      double precision NOT NULL,
    raised_at       timestamp(6) with time zone NOT NULL,
    severity        varchar(16)      NOT NULL,
    status          varchar(16)      NOT NULL,
    threshold_value double precision NOT NULL,
    trigger_value   double precision NOT NULL,
    unit            varchar(16),
    updated_at      timestamp(6) with time zone NOT NULL,
    CONSTRAINT alarm_direction_check CHECK (direction IN ('HIGH', 'LOW')),
    CONSTRAINT alarm_severity_check CHECK (severity IN ('WARNING', 'CRITICAL')),
    CONSTRAINT alarm_status_check CHECK (status IN ('ACTIVE', 'CLEARED'))
);
CREATE INDEX idx_alarm_eq_metric_status ON alarm (equipment_id, metric, status);
CREATE INDEX idx_alarm_raised_at ON alarm (raised_at);

CREATE TABLE work_order (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alarm_id        bigint       NOT NULL,
    body            text         NOT NULL,
    created_at      timestamp(6) with time zone NOT NULL,
    equipment_id    varchar(32)  NOT NULL,
    generator       varchar(32)  NOT NULL,
    metric          varchar(32)  NOT NULL,
    reference_docs  jsonb,
    severity        varchar(16)  NOT NULL,
    summary         varchar(500),
    title           varchar(200) NOT NULL,
    acknowledged_at timestamp(6) with time zone,
    action_taken    text,
    completed_at    timestamp(6) with time zone,
    outcome         varchar(16),
    root_cause      varchar(200),
    status          varchar(16),
    worker          varchar(64),
    CONSTRAINT work_order_outcome_check CHECK (outcome IN ('RESOLVED', 'PARTIAL', 'UNRESOLVED')),
    CONSTRAINT work_order_severity_check CHECK (severity IN ('WARNING', 'CRITICAL')),
    CONSTRAINT work_order_status_check CHECK (status IN ('OPEN', 'ACKNOWLEDGED', 'COMPLETED'))
);
CREATE INDEX idx_work_order_alarm ON work_order (alarm_id);
CREATE INDEX idx_work_order_created_at ON work_order (created_at);
