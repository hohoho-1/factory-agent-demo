-- 제품 전환(체인지오버): 품목이 바뀌면 배합기를 세정(CIP)하고 라인 클리어런스를 확인해야 다음 품목을 시작한다.
--   CLEANING(PLC 세정 중) → CLEANED(세정 완료, 클리어런스 대기) → CLEARED(이전 제품 자재 제거 확인) / FAILED(PLC 거부)
-- production_job_batch.supervisor_*: 오더 도중 다른 품목으로 바꿀 때 생산 책임자 승인 (긴급 주문 등)
CREATE TABLE line_changeover (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_id    varchar(32)  NOT NULL,
    cip_id          varchar(32)  NOT NULL UNIQUE,
    from_item_code  varchar(32),
    from_item_name  varchar(100),
    status          varchar(16)  NOT NULL,
    message         varchar(300),
    requested_by    varchar(64),
    requested_at    timestamp(6) with time zone NOT NULL,
    cleaned_at      timestamp(6) with time zone,
    cleared_by      varchar(64),
    cleared_at      timestamp(6) with time zone,
    CONSTRAINT line_changeover_status_check CHECK (status IN ('CLEANING', 'CLEANED', 'CLEARED', 'FAILED'))
);
ALTER TABLE production_job_batch ADD COLUMN supervisor_by varchar(64);
ALTER TABLE production_job_batch ADD COLUMN supervisor_reason varchar(300);
