-- MES 생산 지시 (ERP 생산 오더를 현장에서 받은 것)와 배치 실행 기록.
-- production_job: ERP 생산 오더 1건. 배합 배치 여러 개로 나눠 돈다.
--   RECEIVED(받음) → IN_PROGRESS(배치 진행 중) → COMPLETED(배치 다 끝남)
-- production_job_batch: 작업자가 시작한 배치 1개. 배치 번호는 MES 가 정한다 ({ERP 오더번호}-{순번}).
--   REQUESTED(PLC 에 요청) → RUNNING(PLC 수락) → COMPLETED(배치 종료) / FAILED(PLC 인터록 거부 등)
--   reported_at: 실적(수량 · 원료 소비)을 ERP 에 보고한 시각. 비어 있으면 다시 보고한다
CREATE TABLE production_job (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    erp_order_no   varchar(32)  NOT NULL UNIQUE,
    item_code      varchar(32)  NOT NULL,
    item_name      varchar(100) NOT NULL,
    qty            int          NOT NULL,
    batches_total  int          NOT NULL,
    batches_done   int          NOT NULL DEFAULT 0,
    produced_qty   int          NOT NULL DEFAULT 0,
    status         varchar(16)  NOT NULL,
    created_at     timestamp(6) with time zone NOT NULL,
    completed_at   timestamp(6) with time zone,
    CONSTRAINT production_job_status_check CHECK (status IN ('RECEIVED', 'IN_PROGRESS', 'COMPLETED'))
);

CREATE TABLE production_job_batch (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id       bigint       NOT NULL REFERENCES production_job (id),
    seq          int          NOT NULL,
    batch_id     varchar(32)  NOT NULL UNIQUE,
    qty          int          NOT NULL,
    status       varchar(16)  NOT NULL,
    message      varchar(300),
    requested_by varchar(64),
    requested_at timestamp(6) with time zone NOT NULL,
    completed_at timestamp(6) with time zone,
    reported_at  timestamp(6) with time zone,
    CONSTRAINT production_job_batch_status_check CHECK (status IN ('REQUESTED', 'RUNNING', 'COMPLETED', 'FAILED')),
    CONSTRAINT production_job_batch_seq UNIQUE (job_id, seq)
);
