-- 품질 영향 판정 (품질 에이전트).
-- 배치 진행 중 알람에 대해 에이전트가 지시서 다음에 판정을 남긴다.
--   level: NO_IMPACT(영향 없음) / INSPECT(추가 검사 필요) / HOLD(배치 홀드 · 출하 보류 권고)
--   status: RECORDED(승인 불필요, 기록만) / PENDING(HOLD, 품질팀 승인 대기) → APPROVED / REJECTED
-- 판정은 규칙(basis)으로 하고, reason 은 판정 이유 설명(LLM 또는 템플릿)이다.

CREATE TABLE quality_assessment (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alarm_id      bigint       NOT NULL,
    work_order_id bigint       NOT NULL,
    batch_id      varchar(32)  NOT NULL,
    batch_phase   varchar(32),
    equipment_id  varchar(32)  NOT NULL,
    metric        varchar(32)  NOT NULL,
    level         varchar(16)  NOT NULL,
    basis         varchar(500) NOT NULL,
    reason        varchar(2000),
    generator     varchar(32),
    status        varchar(16)  NOT NULL,
    created_at    timestamp(6) with time zone NOT NULL,
    decided_by    varchar(64),
    decided_at    timestamp(6) with time zone,
    decision_note varchar(500),
    CONSTRAINT quality_assessment_level_check CHECK (level IN ('NO_IMPACT', 'INSPECT', 'HOLD')),
    CONSTRAINT quality_assessment_status_check CHECK (status IN ('RECORDED', 'PENDING', 'APPROVED', 'REJECTED'))
);
CREATE INDEX idx_quality_assessment_batch ON quality_assessment (batch_id);
CREATE INDEX idx_quality_assessment_work_order ON quality_assessment (work_order_id);
