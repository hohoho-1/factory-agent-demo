-- AI 작업: 작업자의 자연어 질문(QUESTION), 조치 이력 기반 매뉴얼 개선 제안(MANUAL_PROPOSAL).
-- 대시보드가 요청하면(PENDING) 에이전트가 Claude 로 작성해 채운다(DONE). 인수인계 리포트와 같은 흐름.

CREATE TABLE assistant_task (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type         varchar(32)  NOT NULL,
    status       varchar(16)  NOT NULL,
    question     varchar(500),
    equipment_id varchar(32),
    metric       varchar(32),
    generator    varchar(32),
    title        varchar(200),
    body         text,
    created_at   timestamp(6) with time zone NOT NULL,
    completed_at timestamp(6) with time zone,
    CONSTRAINT assistant_task_type_check CHECK (type IN ('QUESTION', 'MANUAL_PROPOSAL')),
    CONSTRAINT assistant_task_status_check CHECK (status IN ('PENDING', 'DONE'))
);
CREATE INDEX idx_assistant_task_created_at ON assistant_task (created_at);
