-- 배치 단계 인식 알람과 알람 일시 억제(shelving).
-- alarm: 발생 시점의 배치 단계·배치 번호 (가상 PLC 모드에서만 채워진다. 단계를 모르면 null)
-- alarm_shelf: 작업자가 정비 등으로 특정 설비(·지표)의 새 알람을 정해진 시간 동안 끄는 기록. 누가 · 왜 · 언제까지.

ALTER TABLE alarm ADD COLUMN batch_phase varchar(32);
ALTER TABLE alarm ADD COLUMN batch_id varchar(32);

CREATE TABLE alarm_shelf (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_id varchar(32)  NOT NULL,
    metric       varchar(32),
    reason       varchar(200) NOT NULL,
    shelved_by   varchar(64)  NOT NULL,
    shelved_at   timestamp(6) with time zone NOT NULL,
    until_at     timestamp(6) with time zone NOT NULL,
    released_by  varchar(64),
    released_at  timestamp(6) with time zone
);
CREATE INDEX idx_alarm_shelf_equipment ON alarm_shelf (equipment_id, until_at);
