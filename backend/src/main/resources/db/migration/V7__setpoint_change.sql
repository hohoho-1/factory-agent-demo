-- 승인형 설정값 제어.
-- setpoint_change: AI 가 지시서와 함께 제안한 설정값 변경(또는 게이트웨이로 직접 들어온 외부 명령의 결과) 1건.
--   PROPOSED → (작업자 승인) SENT → APPLIED(PLC 반영) / INTERLOCKED(PLC 인터록 거부) / FAILED(응답 없음 등)
--   PROPOSED → REJECTED(작업자 거절)
-- setpoint_audit: 상태가 바뀔 때마다 덧붙이는 감사 기록 (누가, 언제, 전후 값). 수정·삭제하지 않는다.

CREATE TABLE setpoint_change (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    origin         varchar(16)  NOT NULL,
    work_order_id  bigint,
    alarm_id       bigint,
    equipment_id   varchar(32)  NOT NULL,
    tag            varchar(64)  NOT NULL,
    label          varchar(100),
    unit           varchar(16),
    current_value  double precision,
    proposed_value double precision NOT NULL,
    reason         varchar(1000),
    sources        varchar(500),
    generator      varchar(32),
    status         varchar(16)  NOT NULL,
    created_at     timestamp(6) with time zone NOT NULL,
    decided_by     varchar(64),
    decided_at     timestamp(6) with time zone,
    decision_note  varchar(500),
    value_before   double precision,
    value_after    double precision,
    result_code    varchar(64),
    result_message varchar(500),
    completed_at   timestamp(6) with time zone,
    CONSTRAINT setpoint_change_origin_check CHECK (origin IN ('AI', 'EXTERNAL')),
    CONSTRAINT setpoint_change_status_check
        CHECK (status IN ('PROPOSED', 'REJECTED', 'SENT', 'APPLIED', 'INTERLOCKED', 'FAILED'))
);
CREATE INDEX idx_setpoint_change_work_order ON setpoint_change (work_order_id);
CREATE INDEX idx_setpoint_change_created_at ON setpoint_change (created_at);

CREATE TABLE setpoint_audit (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    change_id   bigint       NOT NULL REFERENCES setpoint_change (id),
    action      varchar(16)  NOT NULL,
    actor       varchar(64)  NOT NULL,
    value_before double precision,
    value_after  double precision,
    message     varchar(500),
    at          timestamp(6) with time zone NOT NULL
);
CREATE INDEX idx_setpoint_audit_change ON setpoint_audit (change_id);
