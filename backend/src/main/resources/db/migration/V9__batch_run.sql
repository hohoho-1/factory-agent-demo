-- 간이 전자 배치 기록(EBR). 가상 PLC 의 배치 단계 태그로 배치 시작 · 단계 전환 · 종료를 기록한다.
-- phases: 단계별 시작 · 종료 시각과 지표 최소 · 최대 (jsonb). 배치 중 알람 · 조치 · 설정값 변경은 기록 조회 때 시간대로 묶는다.

CREATE TABLE batch_run (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id     varchar(32)  NOT NULL UNIQUE,
    equipment_id varchar(32)  NOT NULL,
    recipe       varchar(100),
    status       varchar(16)  NOT NULL,
    started_at   timestamp(6) with time zone NOT NULL,
    ended_at     timestamp(6) with time zone,
    phases       jsonb,
    CONSTRAINT batch_run_status_check CHECK (status IN ('RUNNING', 'COMPLETED'))
);
CREATE INDEX idx_batch_run_started_at ON batch_run (started_at);
